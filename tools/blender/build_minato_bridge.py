def build_connection_plate():
    """
    Bolted splice plate with a bolt ring - scattered onto rib joints and brace ends so the
    steel reads as assembled rather than extruded. One module, many placements.
    """
    import math as _m
    parts = [M.box("plate", (0.0, 0.0, 0.0), (0.06, 0.92, 0.72), uv_per_m=2.0)]
    for i in range(10):
        a = _m.tau * i / 10.0
        y = 0.32 * _m.cos(a)
        z = 0.25 * _m.sin(a)
        parts.append(M.tube(f"bolt{i}", (0.03, y, z), (0.085, y, z),
                            0.032, segments=6, uv_per_m=3.0))
    obj = M.finish(parts, "grey", bevel=0.006, bevel_segments=1, smooth_angle=36.0)
    M.paint(obj, "steel_dark")
    obj.name = "Minato_Bridge_ConnectionPlate_LOD0"
    return obj


