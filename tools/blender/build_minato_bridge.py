def main():
    write_spec()
    for builder, filename, ratios in KIT:
        S.reset_scene()
        obj = builder()
        M.stat(obj, filename.replace(".fbx", ""))
        exports = [obj]
        base = obj.name.replace("_LOD0", "")
        for i, r in enumerate(ratios):
            lod = M.decimated_copy(obj, f"{base}_LOD{i + 1}", r)
            exports.append(lod)
        M.export_fbx(exports, filename)
        M.save_blend(filename.replace(".fbx", ".blend"))


if __name__ == "__main__":
    main()
