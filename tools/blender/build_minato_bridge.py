def build_cross_brace():
    """
    Horizontal crown strut ONLY, spanning between the two ribs. Origin at the carriageway
    centreline on the rib centreline height. Unity scales X to the rib gap at each station.

    The diagonal members are deliberately NOT in this module: a rib curves between two brace
    stations, so a diagonal baked in at constant height renders as a flat plate punching out
    through the arch silhouette once the module is uniformly scaled. They are placed as
    separate straight members between computed endpoints - see build_brace_diagonal.
    """
    e = K["ribOffsetCrown"] - K["ribWidthCrown"] * 0.25   # embed a quarter-section into the rib
    parts = [M.beam("strut", (-e, 0.0, 0.0), (e, 0.0, 0.0), 0.62, 0.78,
                    up_hint=(0, 1, 0), uv_per_m=0.5)]
