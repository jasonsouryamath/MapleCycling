# ======================================================================== deck bay

def build_deck_bay():
    """
    13.75 m of under-deck structure: twin longitudinal plate girders, cross girders, the soffit
    and the cantilever brackets that carry the footway. Origin at the bay START on the
    carriageway centreline at deck level; the bay runs to +Z.

    The rideable slab itself is NOT here - it is swept continuously by the Unity pass.
    """
    L = K["deckBayLength"]
    go = K["girderOffset"]
    gd = K["girderDepth"]
    slab = K["deckSlabDepth"]
    top = -slab           # underside of the deck slab

    steel = []
    conc = []

    # Longitudinal plate girders, I-section.
    web = 0.14
    flange_w, flange_t = 1.10, 0.10
    for sgn in (-1.0, +1.0):
        x = sgn * go
        steel.append(M.box(f"web{int(sgn)}", (x, top - gd * 0.5, L * 0.5),
                           (web, gd, L), uv_per_m=0.30))
        steel.append(M.box(f"fl_t{int(sgn)}", (x, top - flange_t * 0.5, L * 0.5),
                           (flange_w, flange_t, L), uv_per_m=0.45))
        steel.append(M.box(f"fl_b{int(sgn)}", (x, top - gd + flange_t * 0.5, L * 0.5),
                           (flange_w, flange_t, L), uv_per_m=0.45))
        # Web stiffeners.
        k = 0
        z = 1.72
        while z < L - 0.5:
            steel.append(M.box(f"stf{int(sgn)}_{k}", (x + sgn * 0.14, top - gd * 0.5, z),
                               (0.14, gd - 2 * flange_t, 0.16), uv_per_m=0.8))
            z += 1.72
            k += 1

    # Cross girders and the K-bracing between the two main girders.
    k = 0
    z = 0.0
    while z <= L + 0.01:
        steel.append(M.beam(f"xg{k}", (-go, top - gd + 0.45, z), (go, top - gd + 0.45, z),
                            0.55, 0.85, up_hint=(0, 1, 0), uv_per_m=0.5))
        if z + L / 4.0 <= L + 0.01:
            steel.append(M.beam(f"kb_a{k}", (-go, top - gd + 0.45, z), (0.0, top - 0.35, z + L / 8.0),
                                0.26, 0.30, up_hint=(0, 1, 0), uv_per_m=0.7))
            steel.append(M.beam(f"kb_b{k}", (go, top - gd + 0.45, z), (0.0, top - 0.35, z + L / 8.0),
                                0.26, 0.30, up_hint=(0, 1, 0), uv_per_m=0.7))
        z += L / 4.0
        k += 1

    # Cantilever brackets carrying the footway outside the girders.
    k = 0
    z = 0.86
    while z < L - 0.2:
        for sgn in (-1.0, +1.0):
            steel.append(M.beam(f"cb{int(sgn)}_{k}",
                                (sgn * (go - 0.4), top - 1.35, z),
                                (sgn * (K["deckHalfWidth"] - 0.05), top - 0.06, z),
                                0.16, 0.34, up_hint=(0, 1, 0), uv_per_m=0.8))
        z += 1.72
        k += 1

    # Underside of the concrete deck slab, full deck width. This - NOT a plate under the
    # girders - is what closes the deck against the sky.
    #
    # An earlier pass sealed the soffit across the bottom of the girders instead, which boxed
    # every cross girder and K-brace inside an opaque shell: the under-deck render came back as
    # a smooth floating plank with none of the structure visible, while the tri count happily
    # reported 3,362. An open-soffit plate-girder deck is also what the real thing is - the slab
    # sits ON the girders, so the girders read as deep shadowed beams hanging beneath it.
    conc.append(M.box("slab", (0.0, top - 0.05, L * 0.5),
                      (K["deckHalfWidth"] * 2.0, 0.10, L), uv_per_m=0.22))
    # Edge fascia beam: the deep shadow line that gives a deck its apparent thickness.
    # prism() extrudes along +Z, so its section "right" axis is -X; mirroring the section in
    # its own right axis is what puts the batter on the OUTBOARD face of each edge.
    base_fascia = [(0.0, 0.0), (0.42, -0.14), (0.42, -0.86), (0.0, -1.00)]
    for sgn in (-1.0, +1.0):
        section = [(sr * -sgn, su) for (sr, su) in base_fascia]
        conc.append(M.prism(
            f"fascia{int(sgn)}", section,
            (sgn * K["deckHalfWidth"], top, 0.0),
            (sgn * K["deckHalfWidth"], top, L),
            up_hint=(0, 1, 0), uv_per_m=0.4))

    steel_obj = M.finish(steel, "steel", bevel=0.02, bevel_segments=1, smooth_angle=30.0)
    conc_obj = M.finish(conc, "conc", bevel=0.03, bevel_segments=1, smooth_angle=30.0)
    M.paint(steel_obj, "steel_grey")
    M.paint(conc_obj, "concrete")
    return S.join([steel_obj, conc_obj], "Minato_Bridge_DeckBay_LOD0")


