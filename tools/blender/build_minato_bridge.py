def build_rail_post():
    """
    Steel railing post with its base plate and the bracket lugs the handrails bolt through.
    Origin at the top of the concrete parapet. Instanced every 2.5 m; the rails themselves are
    swept continuously by the Unity pass so they cannot develop a seam.
    """
    h = K["railHeight"]
    parts = [
        M.box("plate", (0.0, 0.012, 0.0), (0.26, 0.024, 0.26), uv_per_m=1.2),
        M.beam("post", (0.0, 0.02, 0.0), (0.0, h, 0.0), 0.08, 0.08,
               up_hint=(0, 0, 1), uv_per_m=0.9),
        M.box("cap", (0.0, h + 0.02, 0.0), (0.12, 0.035, 0.12), uv_per_m=1.2),
    ]
    for hy in (h * 0.42, h * 0.98):
        parts.append(M.box(f"lug{hy:.2f}", (0.0, hy, 0.0), (0.16, 0.075, 0.075), uv_per_m=1.4))
    for sx in (-1, 1):
        parts.append(M.box(f"bolt{sx}", (sx * 0.06, 0.03, 0.0), (0.04, 0.03, 0.04),
                           uv_per_m=2.0))
    obj = M.finish(parts, "post", bevel=0.008, smooth_angle=34.0)
    M.paint(obj, "steel_vermilion")
    obj.name = "Minato_Bridge_RailPost_LOD0"
    return obj


def build_lamp():
    """The tall curved lamp standard from concepts 01-04. Origin at its base."""
    grey = []
    h = 9.4
    grey.append(M.prism("foot", [(-0.30, -0.30), (0.30, -0.30), (0.30, 0.30), (-0.30, 0.30)],
                        (0.0, 0.0, 0.0), (0.0, 0.55, 0.0), up_hint=(0, 0, 1), uv_per_m=0.9))
    grey.append(M.tube("column", (0.0, 0.5, 0.0), (0.0, h, 0.0), 0.115, segments=10,
                       uv_per_m=0.7, taper=0.72))
    # Curved gallows arm reaching out over the carriageway.
    prev = Vector((0.0, h, 0.0))
    for i in range(1, 7):
        f = i / 6.0
        nxt = Vector((-(2.5 * f), h + 1.45 * math.sin(f * math.pi * 0.5), 0.0))
        grey.append(M.tube(f"arm{i}", prev, nxt, 0.085 * (1.0 - 0.25 * f), segments=8,
                           uv_per_m=0.8))
        prev = nxt
    grey.append(M.prism("lum", [(-0.30, -0.10), (0.30, -0.10), (0.26, 0.10), (-0.26, 0.10)],
                        (prev.x - 0.05, prev.y - 0.10, -0.62),
                        (prev.x - 0.05, prev.y - 0.10, 0.62),
                        up_hint=(0, 1, 0), uv_per_m=0.9))
    obj = M.finish(grey, "lamp", bevel=0.01, smooth_angle=34.0)
    M.paint(obj, "lamp_grey")
    obj.name = "Minato_Bridge_Lamp_LOD0"
    return obj


def build_joint():
    """
    Expansion joint: the finger plate running across the carriageway at every span end. Sits
    2 cm proud of nothing - it is inset flush into the swept road so it cannot be a bump.
    """
    w = (K["deckHalfWidth"] - 0.2) * 2.0
    parts = [
        M.box("kerb_l", (0.0, -0.02, -0.26), (w, 0.10, 0.20), uv_per_m=1.0),
        M.box("kerb_r", (0.0, -0.02, 0.26), (w, 0.10, 0.20), uv_per_m=1.0),
        M.box("gap", (0.0, -0.05, 0.0), (w, 0.10, 0.34), uv_per_m=1.0),
    ]
    # Interlocking fingers.
    n = int(w / 0.34)
    for i in range(n):
        x = -w * 0.5 + (i + 0.5) * (w / n)
        z = -0.13 if i % 2 == 0 else 0.13
        parts.append(M.box(f"fing{i}", (x, -0.012, z), (w / n * 0.72, 0.055, 0.30),
                           uv_per_m=1.6))
    obj = M.finish(parts, "joint", bevel=0.004, smooth_angle=34.0)
    M.paint(obj, "steel_dark")
    obj.name = "Minato_Bridge_Joint_LOD0"
    return obj


def build_portal():
    """
    A standalone portal frame for the lower approach spans, where the deck runs on plate
    girders rather than under an arch but still needs visible cross bracing.
    """
    parts = []
    hw = K["deckHalfWidth"] + 0.5
    h = 7.2
    for sx in (-1.0, 1.0):
        parts.append(M.beam(f"leg{int(sx)}", (sx * hw, -0.5, 0.0), (sx * (hw - 0.55), h, 0.0),
                            0.85, 0.95, up_hint=(0, 0, 1), uv_per_m=0.4))
    parts.append(M.beam("head", (-(hw - 0.55), h, 0.0), ((hw - 0.55), h, 0.0),
                        0.80, 1.00, up_hint=(0, 1, 0), uv_per_m=0.4))
    parts.append(M.beam("dl", (-(hw - 0.3), h - 2.2, 0.0), (0.0, h - 0.45, 0.0),
                        0.40, 0.48, up_hint=(0, 1, 0), uv_per_m=0.6))
    parts.append(M.beam("dr", ((hw - 0.3), h - 2.2, 0.0), (0.0, h - 0.45, 0.0),
                        0.40, 0.48, up_hint=(0, 1, 0), uv_per_m=0.6))
    obj = M.finish(parts, "portal", bevel=0.03, smooth_angle=32.0)
    M.paint(obj, "steel_vermilion")
    obj.name = "Minato_Bridge_Portal_LOD0"
    return obj


