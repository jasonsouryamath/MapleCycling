# ======================================================================== arch span

def _arch_f(z):
    """Normalised 0..1 position along the span from a local Z."""
    return (z + K["spanLength"] * 0.5) / K["spanLength"]


def _arch_y(f):
    """Rib centreline height above deck level at normalised position f."""
    return K["archRise"] * (1.0 - (2.0 * f - 1.0) ** 2) - 2.0


def _arch_lean(f):
    return abs(2.0 * f - 1.0)           # 1 at the springing, 0 at the crown


def _arch_x(f, sgn=1.0):
    """Rib centreline offset from the carriageway centreline."""
    lean = _arch_lean(f)
    return sgn * (K["ribOffsetCrown"] +
                  (K["ribOffsetSpring"] - K["ribOffsetCrown"]) * lean)


def _arch_sec(f, scale=1.0):
    """Rib box section (width, depth) at normalised position f."""
    lean = _arch_lean(f)
    w = K["ribWidthCrown"] + (K["ribWidthSpring"] - K["ribWidthCrown"]) * lean
    d = K["ribDepthCrown"] + (K["ribDepthSpring"] - K["ribDepthCrown"]) * lean
    return w * scale, d * scale


def _build_rib(name, sec_scale=1.0, stiffeners=True):
    """
    ONE arch rib, origin at the span centre on the carriageway centreline at deck level.
    Unity instances this twice (mirrored in X) per span - the spec forbids baking the whole
    arch into a single mesh, so the rib is the atomic module.
    """
    n = K["archSegments"]
    span = K["spanLength"]
    half = span * 0.5
    pts, secs = [], []
    for i in range(n + 1):
        f = i / n
        pts.append((_arch_x(f), _arch_y(f), -half + f * span))
        secs.append(_arch_sec(f, sec_scale))

    steel = []
    for i in range(n):
        w0, d0 = secs[i]
        w1, d1 = secs[i + 1]
        steel.append(M.beam(f"rib_{i}", pts[i], pts[i + 1],
                            w0, d0, up_hint=(0, 1, 0), uv_per_m=0.30,
                            taper=(w1 / max(w0, 1e-6))))
    if stiffeners:
        # Visible stiffener plates down the outside face of a welded box arch.
        for i in range(2, n - 1, 2):
            a = Vector(pts[i])
            w, d = secs[i]
            steel.append(M.box(f"rib_st{i}", (a.x + w * 0.5 + 0.06, a.y, a.z),
                               (0.10, d * 0.88, 0.55), uv_per_m=0.6))

    obj = M.finish(steel, "steel", bevel=0.035, bevel_segments=1, smooth_angle=32.0)
    M.paint(obj, "steel_vermilion")
    obj.name = name
    return obj


def build_arch_rib_main():
    """Main arch rib - full section, carries the hangers."""
    return _build_rib("Minato_Bridge_ArchRibMain_LOD0", sec_scale=1.0, stiffeners=True)


def build_arch_rib_secondary():
    """
    Secondary arch rib - the lighter inboard/approach rib. Same curve so it reads as one
    family, 68% section so the pair has a visible primary/secondary hierarchy.
    """
    return _build_rib("Minato_Bridge_ArchRibSecondary_LOD0", sec_scale=0.68, stiffeners=False)


