def build_pier_cap():
    """Pier head: the cross-head under the deck plus its bearings. Origin at deck soffit."""
    hw = K["pierCapHalfWidth"]
    hl = K["pierCapHalfLength"]
    d = K["pierCapDepth"]
    conc = []
    grey = []

    # Flared cross-head - wider at the top where it picks up the girders.
    conc.append(M.prism(
        "cap",
        [(-hw, 0.0), (hw, 0.0), (hw * 0.80, -d * 0.62), (hw * 0.62, -d),
         (-hw * 0.62, -d), (-hw * 0.80, -d * 0.62)],
        (0.0, -0.55, -hl), (0.0, -0.55, hl), up_hint=(0, 1, 0), uv_per_m=0.28))
    # Drip nib and a band of form-work detail.
    conc.append(M.box("band", (0.0, -0.55 - d * 0.62, 0.0),
                      (hw * 1.66, 0.22, hl * 2.06), uv_per_m=0.4))

    # Bearings under each main girder.
    for sgn in (-1.0, +1.0):
        grey.append(M.box(f"brg{int(sgn)}", (sgn * K["girderOffset"], -0.30, 0.0),
                          (1.50, 0.50, 1.50), uv_per_m=0.7))

    c = M.finish(conc, "conc", bevel=0.05, smooth_angle=28.0)
    g = M.finish(grey, "grey", bevel=0.02, smooth_angle=30.0)
    M.paint(c, "concrete")
    M.paint(g, "steel_dark")
    return S.join([c, g], "Minato_Bridge_PierCap_LOD0")


def build_pier_shaft():
    """
    A tileable 10 m pier shaft segment, origin at its TOP, running down to -10.

    Prismatic on purpose: a tapered tile cannot repeat. The batter that makes a pier look like
    a pier lives in the base module, and the shaft carries vertical form joints and a shallow
    recessed panel so a stack of them never reads as one smooth extrusion.
    """
    L = K["pierShaftLength"]
    hw = K["pierShaftHalfWidth"]
    hl = K["pierShaftHalfLength"]
    parts = [M.box("shaft", (0.0, -L * 0.5, 0.0), (hw * 2, L, hl * 2), uv_per_m=0.24)]
    # Recessed panel on each broad face.
    for sgn in (-1.0, +1.0):
        parts.append(M.box(f"panel{int(sgn)}", (0.0, -L * 0.5, sgn * (hl + 0.005)),
                           (hw * 1.46, L - 1.3, 0.14), uv_per_m=0.35))
    # Vertical corner pilasters.
    for sx in (-1.0, 1.0):
        parts.append(M.box(f"pil{int(sx)}", (sx * (hw - 0.22), -L * 0.5, 0.0),
                           (0.44, L, hl * 2 + 0.16), uv_per_m=0.4))
    obj = M.finish(parts, "shaft", bevel=0.04, smooth_angle=28.0)
    M.paint(obj, "concrete")
    obj.name = "Minato_Bridge_PierShaft_LOD0"
    return obj


def build_pier_base():
    """
    The waterline block: battered on all faces with pointed cutwaters at each end to break the
    sea, plus a rock-armour skirt. Origin at its TOP so it stacks under the shaft.
    """
    d = K["pierBaseDepth"]
    hw = K["pierShaftHalfWidth"]
    hl = K["pierShaftHalfLength"]
    conc = []
    rock = []

    bw, bl = hw + 2.6, hl + 3.4     # footprint at the bottom
    # Battered body.
    conc.append(M.prism(
        "body",
        [(-hw - 0.2, 0.0), (hw + 0.2, 0.0), (bw, -d), (-bw, -d)],
        (0.0, 0.0, -hl - 0.2), (0.0, 0.0, hl + 0.2), up_hint=(0, 1, 0), uv_per_m=0.22))
    # Pointed cutwaters.
    for sgn in (-1.0, +1.0):
        conc.append(M.prism(
            "cut",
            [(-hw - 0.2, 0.0), (hw + 0.2, 0.0), (bw, -d), (-bw, -d)],
            (0.0, 0.0, sgn * (hl + 0.2)), (0.0, 0.0, sgn * bl),
            up_hint=(0, 1, 0), uv_per_m=0.22, taper=0.06))
    # Splash band at the waterline - the tide line is what sells scale on a marine pier.
    conc.append(M.box("splash", (0.0, -d + 1.4, 0.0), (bw * 2.02, 1.3, bl * 2.02),
                      uv_per_m=0.35))

    # Rock armour.
    r = M.rng(7)
    for i in range(26):
        a = r.uniform(0, math.tau)
        rad = r.uniform(0.92, 1.18)
        px = math.cos(a) * bw * rad
        pz = math.sin(a) * bl * rad
        s = r.uniform(0.9, 1.9)
        rock.append(M.box(f"arm{i}", (px, -d + s * 0.35, pz), (s, s * 0.8, s * 1.1),
                          uv_per_m=0.5))

    c = M.finish(conc, "conc", bevel=0.06, smooth_angle=26.0)
    rk = M.finish(rock, "rock", bevel=0.05, smooth_angle=34.0)
    M.paint(c, "concrete_wet")
    M.paint(rk, "rock")
    return S.join([c, rk], "Minato_Bridge_PierBase_LOD0")


