"""
MINATO COAST - the modular bridge kit.

Builds the coral-vermilion steel through-arch crossing as a set of INDEPENDENT modules that
Unity instances along the route, plus the JSON spec that keeps the Blender geometry and the
Unity staging pass agreeing about every dimension.

Authored in Unity-local coordinates (+Z forward along the route, +X rider's right, +Y up) and
converted by ``minato_lib``'s beam/tube/prism primitives, which all pass through
``sakura_lib.u2b``. See ``minato_lib`` for the measured FBX round trip.

WHY THESE ARE MODULES AND THE ROAD IS NOT
-----------------------------------------
The brief asks for BOTH "modular bridge pieces" AND "smooth continuous road ... no gaps,
overlaps, bumps, snagging seams, or collider discontinuities". Those pull in opposite
directions: a chain of straight tiles across a curving route cannot be seam-free.

So the split is by what each side is actually good at:

  * Everything the rider RIDES ON or ALONGSIDE - carriageway, markings, kerb, parapet, handrail
    runs, guardrail - is swept as ONE continuous mesh along the route by the Unity pass
    (``MinatoCoastEnvironment``), sharing exact vertices across chunk boundaries. No tiling, so
    no seam can exist.
  * Everything STRUCTURAL and genuinely discrete - arch spans, piers, deck girders, railing
    posts, lamps, expansion joints - is a module here, instanced with clean pivots and LODs.

The one module that sits under the road, the deck bay, is 13.75 m long. On the tightest curve
the bridge actually uses (the ~400 m radius landfall) a straight 13.75 m chord deviates by
13.75^2 / (8 * 400) = 59 mm from the true arc - hidden under the parapet overhang, and never
touched by the rider or a collider.

ALL DIMENSIONS ARE PROVISIONAL ILLUSTRATIVE TUNING unless noted. They are chosen to read like
the concept renders at cycling-camera scale and to be structurally believable, not because the
design fixes them.
"""

